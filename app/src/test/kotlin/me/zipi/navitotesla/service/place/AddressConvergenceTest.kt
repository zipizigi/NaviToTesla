package me.zipi.navitotesla.service.place

import org.junit.Assert.assertEquals
import org.junit.Test

/**
 * 같은 주소를 도로명주소 규격이 허용하는 여러 표기로 쓴 뒤 하나로 수렴하는지 검증.
 * 캐시 키를 만드는 실제 진입점([AddressCanonicalizer.canonicalize])을 통해 확인한다.
 *
 * 규격: `시도 시군구 [읍면] 도로명 [지하]본번[-부번][, 상세주소] [(참고항목)]`
 * - 시도는 단축형·전체명·"~시" 모두 통용
 * - 읍/면은 구성요소, 동/리는 참고항목이라 본 주소에 오지 않음
 * - 지하는 건물번호 앞, 띄어쓰기 유무 혼재
 * - 상세주소(동/층/호)는 쉼표 구분이 규격이나 생략도 흔함
 * - 참고항목은 괄호에 법정동 또는 법정동+건물명
 */
class AddressConvergenceTest {
    private fun assertConverge(
        expected: String,
        vararg variants: String,
    ) {
        variants.forEach { variant ->
            assertEquals("표기: $variant", expected, AddressCanonicalizer.canonicalize(variant))
        }
    }

    @Test
    fun `동 지역 도로명 - 서울특별시청`() =
        assertConverge(
            "서울 중구 세종대로 110",
            "서울 중구 세종대로 110",
            "서울시 중구 세종대로 110",
            "서울특별시 중구 세종대로 110",
            "대한민국 서울특별시 중구 세종대로 110",
            "서울특별시 중구 세종대로 110 (태평로1가)",
            "서울특별시 중구 세종대로 110(태평로1가)",
            "서울특별시 중구 세종대로 110 (태평로1가, 서울특별시청)",
            "서울특별시 중구 세종대로 110, 3층",
            "서울특별시 중구 세종대로 110 3층",
            "서울특별시 중구 세종대로 110 서울특별시청",
            "  서울특별시   중구  세종대로   110  ",
        )

    @Test
    fun `읍 지역 도로명 - 포항역`() =
        assertConverge(
            "경북 포항시 북구 포항역로 1",
            "경북 포항시 북구 포항역로 1",
            "경북 포항시 북구 흥해읍 포항역로 1",
            "경상북도 포항시 북구 흥해읍 포항역로 1",
            "대한민국 경상북도 포항시 북구 흥해읍 포항역로 1",
            "경상북도 포항시 북구 흥해읍 포항역로 1 포항역",
            "경상북도 포항시 북구 흥해읍 포항역로 1, 2층",
        )

    @Test
    fun `면 지역 도로명과 부번 - 여수해상케이블카`() =
        assertConverge(
            "전남광주 여수시 돌산로 3600-1",
            "전남광주 여수시 돌산로 3600-1",
            "전남광주 여수시 돌산읍 돌산로 3600-1",
            "전남광주통합특별시 여수시 돌산읍 돌산로 3600-1",
            "전남광주통합특별시 여수시 돌산읍 돌산로 3600-1 (우두리)",
        )

    @Test
    fun `지하 건물번호 - 수내역`() =
        assertConverge(
            "경기 성남시 분당구 성남대로 491",
            "경기 성남시 분당구 성남대로 491",
            "경기 성남시 분당구 성남대로 지하 491",
            "경기 성남시 분당구 성남대로 지하491",
            "경기도 성남시 분당구 성남대로 지하 491",
            "경기도 성남시 분당구 성남대로 지하 491 (수내동, 수내역)",
            "경기도 성남시 분당구 성남대로 491 수내역 지하1층",
        )

    @Test
    fun `지하 건물번호와 부번 - 신도림역`() =
        assertConverge(
            "서울 구로구 새말로 117-21",
            "서울 구로구 새말로 117-21",
            "서울 구로구 새말로 지하 117-21",
            "서울 구로구 새말로 지하117-21",
            "서울특별시 구로구 새말로 117-21 지하1층",
        )

    @Test
    fun `시군구 없는 특별자치시 - 정부세종청사`() =
        assertConverge(
            "세종 다솜2로 94",
            "세종 다솜2로 94",
            "세종시 다솜2로 94",
            "세종특별자치시 다솜2로 94",
            "대한민국 세종특별자치시 다솜2로 94",
            "세종특별자치시 다솜2로 94 (어진동)",
        )

    @Test
    fun `특별자치도 개편 표기 - 강릉역`() =
        assertConverge(
            "강원 강릉시 용지로 176",
            "강원 강릉시 용지로 176",
            "강원도 강릉시 용지로 176",
            "강원특별자치도 강릉시 용지로 176",
            "강원특별자치도 강릉시 용지로 176 (교동)",
        )

    @Test
    fun `특별자치도 개편 표기 - 전주한옥마을`() =
        assertConverge(
            "전북 전주시 완산구 기린대로 99",
            "전북 전주시 완산구 기린대로 99",
            "전라북도 전주시 완산구 기린대로 99",
            "전북특별자치도 전주시 완산구 기린대로 99",
        )

    @Test
    fun `공동주택 상세주소와 참고항목 - 반포자이`() =
        assertConverge(
            "서울 서초구 신반포로 270",
            "서울 서초구 신반포로 270",
            "서울특별시 서초구 신반포로 270",
            "서울특별시 서초구 신반포로 270, 101동 101호",
            "서울특별시 서초구 신반포로 270 101동 101호",
            "서울특별시 서초구 신반포로 270, 101동 101호 (반포동, 반포자이아파트)",
            "서울특별시 서초구 신반포로 270 (반포동, 반포자이아파트)",
        )

    @Test
    fun `번길 도로명과 상세주소 - 판교`() =
        assertConverge(
            "경기 성남시 분당구 판교로289번길 20",
            "경기 성남시 분당구 판교로289번길 20",
            "경기도 성남시 분당구 판교로289번길 20",
            "경기도 성남시 분당구 판교로289번길 20 (삼평동)",
            "경기도 성남시 분당구 판교로289번길 20, 3층 301호",
        )

    @Test
    fun `상세주소가 길게 붙는 복합시설 - 코엑스`() =
        assertConverge(
            "서울 강남구 영동대로 513",
            "서울 강남구 영동대로 513",
            "서울특별시 강남구 영동대로 513",
            "대한민국 서울특별시 강남구 영동대로 513",
            "서울특별시 강남구 영동대로 513 지하1층 O-107호 라운지",
            "서울특별시 강남구 영동대로 513 스타필드 코엑스몰 지하 1층",
            "서울특별시 강남구 영동대로 513 , B1층",
            "서울특별시 강남구 영동대로 513 (삼성동, 코엑스)",
        )

    @Test
    fun `규격 위반으로 동이 끼어든 표기 - 더현대 서울`() =
        assertConverge(
            "서울 영등포구 여의대로 108",
            "서울 영등포구 여의대로 108",
            "서울특별시 영등포구 여의대로 108",
            "서울특별시 영등포구 여의도동 여의대로 108",
            "서울특별시 영등포구 여의도동 여의대로 108 더현대 서울",
        )

    // === 지번주소 ===

    @Test
    fun `지번 - 서울특별시청`() =
        assertConverge(
            "서울 중구 태평로1가 31",
            "서울 중구 태평로1가 31",
            "서울시 중구 태평로1가 31",
            "서울특별시 중구 태평로1가 31",
            "대한민국 서울특별시 중구 태평로1가 31",
            "서울특별시 중구 태평로1가 31 서울특별시청",
            "서울특별시 중구 태평로1가 31, 3층",
        )

    @Test
    fun `지번 - 읍 유지와 부번`() =
        assertConverge(
            "경북 포항시 북구 흥해읍 이인리 137-1",
            "경북 포항시 북구 흥해읍 이인리 137-1",
            "경상북도 포항시 북구 흥해읍 이인리 137-1",
            "경상북도 포항시 북구 흥해읍 이인리 137-1 포항역",
        )

    @Test
    fun `지번 - 산 번지`() =
        assertConverge(
            "전남광주 북구 금곡동 산 1-1",
            "전남광주 북구 금곡동 산 1-1",
            "전남광주 북구 금곡동 산1-1",
            "전남광주통합특별시 북구 금곡동 산 1-1",
            "전남광주통합특별시 북구 금곡동 산1-1 무등산",
        )

    @Test
    fun `지번 - 번지 없는 곳과 TMAP 0 번지`() =
        assertConverge(
            "경기 안산시 단원구 대부동동",
            "경기 안산시 단원구 대부동동",
            "경기 안산시 단원구 대부동동 0",
            "경기도 안산시 단원구 대부동동",
            "대한민국 경기도 안산시 단원구 대부동동",
        )

    // === 수렴 대상이 아닌 것 (정보가 소실되어 복원 불가) ===

    @Test
    fun `시도가 생략된 표기는 별개 키로 남음`() {
        // 도로명은 시군구 단위로만 고유해 시도·시군구를 복원할 수 없음.
        assertEquals("강남구 영동대로 513", AddressCanonicalizer.canonicalize("강남구 영동대로 513"))
        assertEquals("영동대로 513", AddressCanonicalizer.canonicalize("영동대로 513"))
    }

    @Test
    fun `시군구가 다르면 같은 도로명 건물번호라도 구분 유지`() {
        // 강남구 도곡로 434 와 송파구 도곡로 434 는 모두 실존.
        assertEquals("서울 강남구 도곡로 434", AddressCanonicalizer.canonicalize("서울특별시 강남구 도곡로 434"))
        assertEquals("서울 송파구 도곡로 434", AddressCanonicalizer.canonicalize("서울특별시 송파구 도곡로 434"))
    }
}
